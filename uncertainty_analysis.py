"""
Deeper analysis of the conformal uncertainty quantification — going beyond
a single coverage percentage to show the intervals are meaningful, not just
present.

Produces (numbers to outputs/uncertainty_analysis.json, figures to
outputs/figures/):

  1. Reliability diagram: coverage at MULTIPLE target levels (50%, 70%, 80%,
     90%, 95%) vs the nominal target — a single 90% number can look fine by
     chance; checking multiple levels shows whether calibration holds
     generally or was a coincidence at one alpha.
  2. Interval width distribution: are intervals a sensible, usably tight
     size, or so wide they're vacuous? (this is exactly what made "pooled"
     conformal's 100%/4% swings meaningless in your earlier runs)
  3. Coverage vs. interval width per dataset: shows the tightness/coverage
     tradeoff per group, making explicit why small groups need wider
     intervals to hit the same target.
  4. Uncertainty vs. absolute error correlation: if the model's MC-Dropout
     uncertainty estimate is informative, samples it's LESS confident about
     should tend to have LARGER actual errors. Reports the correlation —
     this is what turns "we report uncertainty" into "the uncertainty means
     something."
  5. Expected Calibration Error (ECE) for regression intervals: a single
     scalar summarizing miscalibration across levels (lower = better
     calibrated), the standard metric reviewers expect for this kind of claim.

Requires the *_predictions.npz files (which include mc_std, lower, upper)
saved by train_one() — run train.py or experiments.py first.

Run:
    python uncertainty_analysis.py
"""

import os
import json
import glob
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import config
from train import load_cached

ALPHA_LEVELS = [0.5, 0.3, 0.2, 0.1, 0.05]  # -> targets of 50%, 70%, 80%, 90%, 95%
FIG_DIR = os.path.join(config.OUTPUT_DIR, "figures")


def _find_best_predictions():
    """Prefers a known-current source over the generic 'best_' file, since
    'best_' is only regenerated by running train.py directly — if you've
    since re-run experiments.py on a different dataset composition (e.g.
    after adding BIT/XJTU/RWTH), 'best_predictions.npz' can silently be
    stale while looking like a valid file. conformal_normalized_groupwise
    and ablation_full are both guaranteed fresh by experiments.py's own
    dataset-signature staleness check, so check those first."""
    candidates = glob.glob(os.path.join(config.OUTPUT_DIR, "*predictions.npz"))
    for preferred in ["conformal_normalized_groupwise", "ablation_full"]:
        match = [p for p in candidates if preferred in os.path.basename(p)]
        if match:
            return match[0]
    best = [p for p in candidates if os.path.basename(p).startswith("best_")]
    if best:
        print("  [!] WARNING: using 'best_predictions.npz' — this file is only "
              "refreshed by running train.py directly, so if your dataset "
              "composition has changed since then (e.g. new datasets added), "
              "this could be STALE. Prefer running experiments.py's ablation "
              "section results instead if available.")
        return best[0]
    return candidates[0] if candidates else None


def analyze():
    pred_path = _find_best_predictions()
    if pred_path is None:
        print("[uncertainty_analysis] no *predictions.npz found — run train.py first")
        return None
    preds = np.load(pred_path, allow_pickle=True)
    y_test = preds["y_test"]
    mean_pred = preds["mean_pred"]
    mc_std = preds["mc_std"]
    lower = preds["lower"]
    upper = preds["upper"]
    lab_test = preds["lab_test"]

    results = {}

    # ---- 1 & 5: reliability across multiple alpha levels + ECE ----
    # We don't have saved val predictions, so we approximate each alpha's
    # interval by SCALING the existing 90%-calibrated half-width by the
    # ratio of normal-quantiles for each target level. This is an approximation
    # (assumes roughly proportional residual quantiles across levels) — good
    # enough to show the QUALITATIVE calibration trend; note this approximation
    # explicitly if you report it.
    from scipy.stats import norm
    base_alpha = config.CONFORMAL_ALPHA
    base_halfwidth = np.abs(upper - lower) / 2  # per-sample (per-group) half-width already computed
    base_z = norm.ppf(1 - base_alpha / 2)

    reliability = []
    for alpha in ALPHA_LEVELS:
        z = norm.ppf(1 - alpha / 2)
        scale = z / base_z
        lo = mean_pred - base_halfwidth * scale
        hi = mean_pred + base_halfwidth * scale
        coverage = float(np.mean((y_test >= lo) & (y_test <= hi)))
        target = 1 - alpha
        reliability.append({"target": target, "actual_coverage": coverage,
                            "abs_calibration_error": abs(coverage - target)})
        print(f"  target={target:.0%}  actual={coverage:.2%}  "
              f"|error|={abs(coverage - target):.2%}")
    ece = float(np.mean([r["abs_calibration_error"] for r in reliability]))
    print(f"[uncertainty_analysis] Expected Calibration Error (ECE, approx.) = {ece:.4f}")
    results["reliability"] = reliability
    results["ece_approx"] = ece
    results["ece_note"] = ("Approximated by Gaussian-quantile scaling of the single "
                           "calibrated 90% interval, not independently recalibrated "
                           "at each level — report as an approximation, not an exact ECE.")

    fig, ax = plt.subplots(figsize=(6, 6))
    targets = [r["target"] for r in reliability]
    actuals = [r["actual_coverage"] for r in reliability]
    ax.plot([0, 1], [0, 1], "k--", lw=1, label="perfect calibration")
    ax.plot(targets, actuals, "o-", color="#4c72b0", label="observed")
    ax.set_xlabel("Nominal (target) coverage")
    ax.set_ylabel("Empirical (actual) coverage")
    ax.set_title(f"Reliability diagram (approx. ECE={ece:.4f})")
    ax.legend()
    os.makedirs(FIG_DIR, exist_ok=True)
    fig.savefig(os.path.join(FIG_DIR, "reliability_diagram.png"), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  saved {os.path.join(FIG_DIR, 'reliability_diagram.png')}")

    # ---- 2: interval width distribution ----
    widths = upper - lower
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.hist(widths, bins=50, color="#55a868", alpha=0.8)
    ax.set_xlabel("Prediction interval width (normalized SOH)")
    ax.set_ylabel("Frequency")
    ax.set_title(f"Interval width distribution (mean={np.mean(widths):.4f})")
    fig.savefig(os.path.join(FIG_DIR, "interval_width_distribution.png"), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  saved {os.path.join(FIG_DIR, 'interval_width_distribution.png')}")
    results["interval_width_mean"] = float(np.mean(widths))
    results["interval_width_std"] = float(np.std(widths))

    # ---- 3: coverage vs width per dataset ----
    per_dataset = {}
    for ds in np.unique(lab_test):
        mask = lab_test == ds
        cov = float(np.mean((y_test[mask] >= lower[mask]) & (y_test[mask] <= upper[mask])))
        w = float(np.mean(widths[mask]))
        per_dataset[ds] = {"coverage": cov, "mean_width": w}
    print("\n[uncertainty_analysis] per-dataset coverage vs. width:")
    for ds, v in per_dataset.items():
        print(f"  {ds}: coverage={v['coverage']:.2%}  mean_width={v['mean_width']:.4f}")
    results["per_dataset_coverage_width"] = per_dataset

    fig, ax = plt.subplots(figsize=(7, 5))
    for ds, v in per_dataset.items():
        ax.scatter(v["mean_width"], v["coverage"] * 100, s=80, label=ds)
    ax.axhline((1 - config.CONFORMAL_ALPHA) * 100, color="k", ls="--", lw=1, label="target")
    ax.set_xlabel("Mean interval width")
    ax.set_ylabel("Coverage (%)")
    ax.set_title("Coverage vs. interval width, per dataset")
    ax.legend()
    fig.savefig(os.path.join(FIG_DIR, "coverage_vs_width.png"), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  saved {os.path.join(FIG_DIR, 'coverage_vs_width.png')}")

    # ---- 4: uncertainty vs. absolute error correlation ----
    abs_error = np.abs(y_test - mean_pred)
    corr = float(np.corrcoef(mc_std, abs_error)[0, 1])
    print(f"\n[uncertainty_analysis] correlation(MC-Dropout std, |error|) = {corr:.4f}")
    if corr > 0.3:
        print("  -> meaningful positive correlation: higher predicted uncertainty "
              "DOES tend to coincide with larger actual errors (uncertainty is informative).")
    elif corr > 0.1:
        print("  -> weak positive correlation: some informativeness, but not strong.")
    else:
        print("  -> little to no correlation: MC-Dropout uncertainty does NOT reliably "
              "track actual error magnitude — report this honestly as a limitation of "
              "the uncertainty estimate itself (separate from the conformal interval's "
              "coverage guarantee, which holds regardless of this correlation).")
    results["uncertainty_error_correlation"] = corr

    fig, ax = plt.subplots(figsize=(7, 5))
    ax.scatter(mc_std, abs_error, s=3, alpha=0.2, color="#4c72b0")
    ax.set_xlabel("MC-Dropout predicted std (uncertainty)")
    ax.set_ylabel("Actual absolute error")
    ax.set_title(f"Uncertainty vs. error (correlation={corr:.3f})")
    fig.savefig(os.path.join(FIG_DIR, "uncertainty_vs_error.png"), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  saved {os.path.join(FIG_DIR, 'uncertainty_vs_error.png')}")

    os.makedirs(config.OUTPUT_DIR, exist_ok=True)
    with open(os.path.join(config.OUTPUT_DIR, "uncertainty_analysis.json"), "w") as fh:
        json.dump(results, fh, indent=2)
    print(f"\n[uncertainty_analysis] saved to {config.OUTPUT_DIR}/uncertainty_analysis.json")
    return results


if __name__ == "__main__":
    analyze()