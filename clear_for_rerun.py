"""
Clear everything generated by the pipeline (cache, trained models, predictions,
results, figures) before rerunning with the corrected CALCE loader.

SAFE BY DEFAULT: dry-run. It only PRINTS what it would delete unless you pass
--yes. Nothing is removed on a plain `python clear_for_rerun.py`.

WHAT IT TARGETS (only inside config.CACHE_DIR and config.OUTPUT_DIR):
  cache/  : every *.npz  (processed.npz and any processed_*.npz variant --
            window-size or seed variants all cache stale, pre-fix CALCE data)
  outputs/: trained model checkpoints (*_model.pt), conformal prediction
            arrays (conformal_*.npz), every *_results.json / *.json result
            file, the CALCE loader diagnostic CSVs (calce_*.csv), and every
            *.png figure (regenerate these with the plot_*.py scripts after
            rerunning, since the old ones were drawn from the corrupted data).

WHAT IT NEVER TOUCHES: any .py file, config.py, the raw dataset folders
(ROOT_DIR / NASA_DIR / CALCE_DIRS / OXFORD_MAT / MIT_DIR / BIT_DIR / XJTU_DIR /
RWTH_DIR), or anything outside config.CACHE_DIR and config.OUTPUT_DIR. It also
skips config.CACHE_DIR/config.OUTPUT_DIR themselves (only their contents), so
the folders remain and don't need recreating.

Figures are searched for in BOTH config.OUTPUT_DIR and the project root itself
(non-recursively, so raw dataset subfolders are never touched), in case a
plot script saves outside outputs/.

USAGE
  python clear_for_rerun.py            # dry run: lists what would be deleted
  python clear_for_rerun.py --yes      # actually deletes it
  python clear_for_rerun.py --yes --keep-figures   # keep the *.png files
"""

import argparse
import os

import config

CACHE_PATTERNS = ["*.npz"]
OUTPUT_PATTERNS = [
    "*_model.pt",
    "conformal_*.npz",
    "*_results.json",
    "*.json",              # catches everything else: hierarchical_*.json,
                            # persistence_baselines.json, real_unit_baselines.json,
                            # predictor_consistent_recalibration.json, etc.
    "calce_*.csv",
]
FIGURE_PATTERN = "*.png"

# Figures are matched in TWO places: config.OUTPUT_DIR (where the training/
# calibration pipeline saves everything else) AND the project root -- the same
# folder config.py lives in -- in case a plot_*.py script saves there instead.
# The root search is NON-RECURSIVE (glob "*.png" only matches direct children,
# never descends into subfolders), so it can never reach into a raw dataset
# folder like "5. Battery Data Set/" or "CS2_33/".


def _glob(root, patterns):
    import glob
    found = set()
    for pat in patterns:
        found.update(glob.glob(os.path.join(root, pat)))
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yes", action="store_true", help="actually delete (default is dry-run)")
    ap.add_argument("--keep-figures", action="store_true", help="don't delete outputs/*.png")
    args = ap.parse_args()

    project_root = os.path.dirname(os.path.abspath(config.__file__))

    targets = set()
    targets |= _glob(config.CACHE_DIR, CACHE_PATTERNS)
    targets |= _glob(config.OUTPUT_DIR, OUTPUT_PATTERNS)
    if not args.keep_figures:
        targets |= _glob(config.OUTPUT_DIR, [FIGURE_PATTERN])
        targets |= _glob(project_root, [FIGURE_PATTERN])   # non-recursive: top-level only

    # never delete a directory, and never delete anything outside these three known,
    # non-recursively-searched roots (belt-and-suspenders check)
    safe_roots = (os.path.abspath(config.CACHE_DIR), os.path.abspath(config.OUTPUT_DIR), project_root)
    targets = sorted(
        p for p in targets
        if os.path.isfile(p) and os.path.abspath(p).startswith(safe_roots)
    )

    if not targets:
        print("nothing to delete -- cache/ and outputs/ are already clean")
        return

    print(f"{'WILL DELETE' if args.yes else 'DRY RUN -- would delete'} {len(targets)} file(s):\n")
    for p in targets:
        print(" ", p)

    if not args.yes:
        print(f"\nre-run with --yes to actually delete these {len(targets)} files")
        return

    removed, failed = 0, []
    for p in targets:
        try:
            os.remove(p)
            removed += 1
        except OSError as e:
            failed.append((p, str(e)))

    print(f"\ndeleted {removed} of {len(targets)} files")
    if failed:
        print(f"{len(failed)} could not be deleted:")
        for p, err in failed:
            print(f"  {p}: {err}")


if __name__ == "__main__":
    main()