"""
clear_stale_xjtu_cache.py

Run this ONCE, right before your next `python experiments.py`, to force a
full regeneration on the corrected XJTU data.

Why this is needed: experiments.py's resume/staleness check
(_current_dataset_signature / _load_existing_result) only fingerprints
WHICH datasets are present in a cached run (via np.unique(lab_test)). It
has no way to detect that XJTU's row-level VALUES changed (795
calibration-block rows removed) while XJTU is still present as a dataset
name. So without this cleanup, experiments.py will report "signature
matches, skipping retraining" for every run and silently hand back the
OLD, contaminated numbers -- defeating the xjtu_loader.py fix entirely.

This script does NOT touch xjtu_loader.py, config.py, or any raw data --
it only deletes derived/cached files so they get regenerated from scratch.

What gets deleted:
  1. Every *.npz file under config.CACHE_DIR (the preprocessed feature
     cache -- includes the default window and any window-specific
     variants like a window=30/50 cache, whatever your preprocessing.py
     actually names them).
  2. Every *_results.json under config.OUTPUT_DIR (every run's cached
     result: baselines, ablations, conformal modes, window sizes,
     multiseed runs, all 7 LODO runs -- XJTU touches essentially all of
     them, either as test data directly or as training data for every
     other dataset's LODO run, so this clears everything rather than
     risk missing one).
  3. experiment_summary.json / experiment_summary.md (the old rolled-up
     summary -- stale the moment any underlying result is stale).

What is intentionally LEFT ALONE:
  - Prediction files (*_predictions.npz), figures (outputs/figures/*.png),
    and any manuscript/report files -- these are regenerated by later
    steps (plots.py, remaining_analysis.py) or edited by hand, not by
    experiments.py itself, and this script's job is narrowly to force
    experiments.py to retrain rather than to do a full project wipe.
    Re-run plots.py and remaining_analysis.py again after experiments.py
    finishes, same as before, once the new numbers exist.

Usage:
    python clear_stale_xjtu_cache.py            # asks for confirmation
    python clear_stale_xjtu_cache.py --yes       # no confirmation prompt
    python clear_stale_xjtu_cache.py --dry-run   # lists what WOULD be
                                                  # deleted, deletes nothing
"""

import os
import sys
import glob

import config  # your existing project config.py


def _find_targets():
    targets = []

    cache_dir = getattr(config, "CACHE_DIR", None)
    if cache_dir and os.path.isdir(cache_dir):
        targets += sorted(glob.glob(os.path.join(cache_dir, "**", "*.npz"), recursive=True))
    elif cache_dir:
        print(f"  [!] config.CACHE_DIR is set to {cache_dir!r} but that directory "
              f"doesn't exist -- nothing to clear there (maybe it hasn't been "
              f"created yet, which is fine).")
    else:
        print("  [!] config.CACHE_DIR is not defined in config.py -- skipping "
              "cache-file cleanup. Check config.py for the actual attribute "
              "name if preprocessing writes its cache somewhere else.")

    output_dir = getattr(config, "OUTPUT_DIR", None)
    if output_dir and os.path.isdir(output_dir):
        targets += sorted(glob.glob(os.path.join(output_dir, "*_results.json")))
        for name in ("experiment_summary.json", "experiment_summary.md"):
            p = os.path.join(output_dir, name)
            if os.path.exists(p):
                targets.append(p)
    elif output_dir:
        print(f"  [!] config.OUTPUT_DIR is set to {output_dir!r} but that "
              f"directory doesn't exist -- nothing to clear there.")
    else:
        print("  [!] config.OUTPUT_DIR is not defined in config.py -- skipping "
              "results-file cleanup.")

    # de-dupe while preserving order, in case CACHE_DIR and OUTPUT_DIR overlap
    seen = set()
    deduped = []
    for t in targets:
        if t not in seen:
            seen.add(t)
            deduped.append(t)
    return deduped


def main():
    dry_run = "--dry-run" in sys.argv
    skip_confirm = "--yes" in sys.argv or dry_run

    targets = _find_targets()

    if not targets:
        print("\nNothing found to delete. Either everything's already clean, "
              "or config.CACHE_DIR/config.OUTPUT_DIR don't match what's "
              "printed above -- double check those paths in config.py if "
              "you expected files here.")
        return

    print(f"\n{'Would delete' if dry_run else 'Will delete'} {len(targets)} file(s):")
    for t in targets:
        print(f"  {t}")

    if dry_run:
        print("\n[dry run] nothing was actually deleted. Re-run without "
              "--dry-run to actually clear these.")
        return

    if not skip_confirm:
        resp = input(f"\nDelete these {len(targets)} file(s)? This forces a full "
                      f"re-run of experiments.py -- expect the full ~15-run "
                      f"training suite to redo from scratch. [y/N] ").strip().lower()
        if resp != "y":
            print("Aborted -- nothing deleted.")
            return

    n_deleted = 0
    n_failed = 0
    for t in targets:
        try:
            os.remove(t)
            n_deleted += 1
        except OSError as e:
            print(f"  [!] failed to delete {t}: {e}")
            n_failed += 1

    print(f"\nDeleted {n_deleted} file(s)"
          + (f", {n_failed} failed" if n_failed else "") + ".")
    print("Now run: python experiments.py")
    print("Every section should print training/[resume]-miss messages "
          "rather than 'signature matches, skipping retraining' this time.")


if __name__ == "__main__":
    main()
